class PerfilConductor {
  final String id;
  final String nombreCompleto;
  final String email;
  final String telefono;
  final String estadoAprobacion;
  final String estadoDisponibilidad;
  final String vehiculoMarca;
  final String vehiculoModelo;
  final String vehiculoColor;
  final String vehiculoPlaca;

  const PerfilConductor({
    required this.id,
    required this.nombreCompleto,
    required this.email,
    required this.telefono,
    required this.estadoAprobacion,
    required this.estadoDisponibilidad,
    required this.vehiculoMarca,
    required this.vehiculoModelo,
    required this.vehiculoColor,
    required this.vehiculoPlaca,
  });
}
